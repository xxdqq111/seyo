/* ======================================================================
   判断这件事发生在什么时候
   ----------------------------------------------------------------------
   规则表（text.mjs 的 TIME_WORDS）能认"文革""八十年代""年轻时"这种明确的词，
   但老人说话经常是**前后一起说**的：

     "我进厂那年刚满二十，一个月挣十八块五"
     "那会儿我还没结婚呢，住在厂里的集体宿舍"
     "过了两年才调回城里"

   这些句子里时间是"那年""那会儿""过了两年"—— 规则认不出绝对年份，
   整件事就掉进时间轴的"时间未定"。所以让**大模型结合上下文判**。

   它比规则强的地方：
     · 能用上前面刚说的话（"那年"指哪一年）
     · 能把年龄换成年份（"刚满二十" + 知道他现在 78 岁 → 1968 年）
     · 能处理相对说法（"过了两年"）

   但也要求它**拿不准就说不知道** —— 宁可放"时间未定"，
   也别瞎编一个年份把时间轴搞乱。
   ====================================================================== */
export function buildTimeMessages({ persona = {}, items = [], history = [], birthYear = null, thisYear = null }) {
  const call = persona.elder_call || '爷爷';
  const now = thisYear || new Date().getFullYear();
  const age = birthYear ? now - Number(birthYear) : null;

  const list = items.map((it, i) => `  ${i + 1}. ${it.statement}`).join('\n');
  const hist = history.length
    ? history.map((h) => `${h.role === 'user' ? call : '你'}：${h.content}`).join('\n')
    : '（没有更早的对话）';

  const system = `你是个档案整理员。下面有几句老人讲过的话，请判断**每件事各发生在哪一年**。

【关于这位老人】
${birthYear ? `· 出生年份：${birthYear} 年（今年 ${now} 年，${age} 岁）` : `· 出生年份：不知道（那就别拿年龄倒推年份）`}
· 他住在国内，讲的是自己这辈子的事。

【他刚才说的话（判断"那年""那会儿""过了两年"指哪一年，靠这个）】
${hist}

【要判断的句子】
${list}

【怎么判】
1. 句子里直接有年份 → 用那个年份。例："八三年分了两间房" → 1983
2. 有能对上年份的说法 → 用那个说法。例："文革第三年" → 1968
   · 参考：解放 1949、抗美援朝 1950-1953、三年困难 1959-1961、
     文革 1966-1976、上山下乡 1968-1978、改革开放 1978
3. 只有年龄 → 用出生年份倒推。例：1950 年生，"二十岁进的厂" → 1970
4. 只有相对说法 → 结合【他刚才说的话】推。例：前一句说 1968 年，
   这句说"过了两年" → 1970
5. **能看出是哪个人生阶段，也要给个大概年份**（时间轴靠它排序，
   不给就全堆到"时间未定"里去）：
   · 童年 / 小时候      → 大约 6~12 岁那年
   · 上学 / 念书        → 大约 10~16 岁
   · 青年 / 年轻时候    → 大约 20~28 岁
   · 刚参加工作 / 进厂  → 大约 18~22 岁
   · 中年 / 上有老下有小 → 大约 40~50 岁
   · 后来 / 再后来      → 结合上文推；推不出就往后挪十年
   这种是**估计**，label 里要写清"大约""前后"。
6. **一点线索都没有才写 null。** 但真没线索就别编 ——
   比如"我今天挺高兴的"这种没头没尾的，null 就 null。

【重点】"那时候""那会儿""那时候""过了两年"这类词**不能当成判断不出来**——
回去看【他刚才说的话】，前面刚提过的年份就是它指的年份。
老人讲话本来就是前后连着说的，别把每句拆开看。

【输出格式】
严格只输出一个**合法 JSON** 数组。不要解释、不要代码块标记。
**键和字符串值都必须加双引号** —— 不要写 {i:1} 这种，那不是 JSON。

✓ 正确（照这个格式）：
[{"i":1,"year":1968,"label":"1968 年前后"},{"i":2,"year":null,"label":""}]

✗ 错误（不要这样）：
[{i:1,year:1968,label:1968 年前后}]

· i     —— 上面列表里的编号（从 1 开始）
· year  —— 四位年份，推不出来就 null
· label —— 十个字以内的时期说明（"1968 年前后""八十年代末""刚参加工作那几年"），
           year 是 null 时也要写清楚是什么时期，实在没有就空字符串`;

  return [
    { role: 'system', content: system },
    { role: 'user', content: '请判断上面这些句子各发生在哪一年，只输出 JSON 数组。' },
  ];
}