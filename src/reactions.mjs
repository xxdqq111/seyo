/** 命中哪一类内容（按命中词长度优先，长的更具体） */
export function matchReaction(a) {
  const text = `${a.cleaned || ''} ${(a.events || []).join(' ')} ${(a.places || []).join(' ')}`;
  let best = null;
  for (const r of REACTIONS) {
    const m = text.match(r.when);
    if (!m) continue;
    const score = m[0].length;
    if (!best || score > best.score) best = { rule: r, score, hit: m[0] };
  }
  return best;
}

/**
 * 顺着内容问：一次只问一件，问过的、跟这次内容无关的不问
 * @returns {string} 追问句
 */
export function contentQuestion(a, story, call) {
  const storyText = story?.statement || '';
  const asked = new Set(story?.asked || []);
  const ok = (q) => q && q !== story?.lastQ && !asked.has(q);

  const hit = matchReaction(a);
  if (hit) {
    for (const q of hit.rule.ask) if (ok(q)) return q;
  }
  // 讲到具体的人 → 问这个人
  const who = (a.persons || [])[0];
  if (who) {
    const pool = [`${who}后来怎么样啦？`, `${who}是您什么人呀？`, `您跟${who}是怎么认识的？`];
    for (const q of pool) if (ok(q)) return q;
  }
  return '';
}

/** 接一句"听懂了"的话（同一个话题不重复用同一句） */
export function contentRemark(a, story) {
  const hit = matchReaction(a);
  if (!hit) return '';
  const list = hit.rule.say;
  const last = story?.lastRemark || '';
  const pick = list.filter((x) => x !== last);
  const chosen = (pick.length ? pick : list)[Math.floor(Math.random() * (pick.length || list.length))];
  if (story) story.lastRemark = chosen;
  return chosen;
}
